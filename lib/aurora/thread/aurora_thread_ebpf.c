/* ---------------------------------------------------------------
 * Module-private state
 * --------------------------------------------------------------- */
static aurora_thread_stats_t          *g_ts = NULL;
static uint32_t                        g_interval_ms = 100;
static struct aurora_thread_ebpf_bpf  *g_skel = NULL;

/* OCUDU: tid_stats totals read at the previous collection, indexed like
 * g_ts->threads[]. Kept here, not in the shared-memory slot, whose layout
 * must stay identical for OAI-compatible readers. */
typedef struct {
    pid_t                          tid;    /* TID the totals belong to; 0 when unused */
    struct aurora_bpf_thread_stats totals;
} ebpf_slot_prev_t;
static ebpf_slot_prev_t g_prev[AURORA_MAX_MONITORED_THREADS];

/* OCUDU: number of the collection interval in progress, mirrored into the
 * interval_epoch BPF map. Starts at 1 so that it never matches the zero
 * epoch of a freshly created tid_stats entry. */
static __u64 g_epoch = 1;

/* ---------------------------------------------------------------
 * Identify our own pid namespace, so the BPF program can translate raw
 * host-namespace tracepoint TIDs into the same namespace
 * aurora_thread_registry.c's /proc/self/task walk uses (see
 * aurora_thread_ebpf.bpf.c's file header for why this is required —
 * without it, TID collisions with unrelated host/other-container tasks
 * silently corrupt the collected data whenever this runs in a container).
 * --------------------------------------------------------------- */
static int get_own_pidns_id(__u64 *dev_out, __u64 *ino_out)
{
    struct stat st;
    if (stat("/proc/self/ns/pid", &st) != 0) {
        fprintf(stderr, "AURORA: stat(/proc/self/ns/pid) failed: %s\n", strerror(errno));
        return -1;
    }
    *dev_out = (__u64)st.st_dev;
    *ino_out = (__u64)st.st_ino;
    return 0;
}

/* ---------------------------------------------------------------
 * Populate tid_filter map with all currently registered TIDs
 * --------------------------------------------------------------- */
static void ebpf_update_tid_filter(void)
{
    if (!g_skel || !g_ts)
        return;

    int filter_fd = bpf_map__fd(g_skel->maps.tid_filter);
    if (filter_fd < 0)
        return;

    uint32_t n = atomic_load_explicit(&g_ts->num_threads, memory_order_relaxed);
    for (uint32_t i = 0; i < n && i < AURORA_MAX_MONITORED_THREADS; i++) {
        aurora_thread_metrics_t *m = &g_ts->threads[i];
        if (!m->valid || m->tid <= 0)
            continue;
        uint32_t tid = (uint32_t)m->tid;
        uint8_t  val = 1;
        bpf_map_update_elem(filter_fd, &tid, &val, BPF_ANY);
    }
}

/* ---------------------------------------------------------------
 * Read BPF tid_stats map and merge into shared memory
 *
 * OCUDU: one lookup per monitored slot instead of a get_next_key walk, and
 * no writes to tid_stats. The OAI agent reset each entry during the walk;
 * a hash map update re-inserts the element at the head of its bucket, so
 * two TIDs sharing a bucket made get_next_key alternate between them
 * forever. Counters are cumulative, so the per-interval values are deltas
 * against the totals read the previous interval (aurora_ebpf_merge_interval).
 * --------------------------------------------------------------- */
static void ebpf_read_and_merge(void)
{
    if (!g_skel || !g_ts)
        return;

    int stats_fd = bpf_map__fd(g_skel->maps.tid_stats);
    if (stats_fd < 0)
        return;

    struct timespec ts_now;
    clock_gettime(CLOCK_MONOTONIC, &ts_now);
    uint64_t now_ns = (uint64_t)ts_now.tv_sec * 1000000000ULL + (uint64_t)ts_now.tv_nsec;

    uint32_t n = atomic_load_explicit(&g_ts->num_threads, memory_order_relaxed);
    for (uint32_t i = 0; i < n && i < AURORA_MAX_MONITORED_THREADS; i++) {
        aurora_thread_metrics_t *m = &g_ts->threads[i];
        if (!m->valid || m->tid <= 0)
            continue;

        /* A slot taken over by another thread starts from zero totals. */
        if (g_prev[i].tid != m->tid) {
            memset(&g_prev[i], 0, sizeof(g_prev[i]));
            g_prev[i].tid = m->tid;
        }

        uint32_t                       key = (uint32_t)m->tid;
        struct aurora_bpf_thread_stats now = {0};
        if (bpf_map_lookup_elem(stats_fd, &key, &now) != 0)
            continue; /* not scheduled since it was added to tid_filter */

        aurora_ebpf_merge_interval(m, &g_prev[i].totals, &now, g_epoch);
        m->timestamp_ns = now_ns;
    }
}

/* ---------------------------------------------------------------
 * OCUDU: drop the BPF entries of threads whose slot was freed or taken over
 * by another thread during the last discovery (@before holds the slot TIDs
 * from before it). Entries are no longer reset, so without this they would
 * pile up for exited threads, and a reused TID would inherit old totals.
 * Single deletes outside of any map walk.
 * --------------------------------------------------------------- */
static void ebpf_forget_exited_threads(const pid_t *before)
{
    int stats_fd  = bpf_map__fd(g_skel->maps.tid_stats);
    int filter_fd = bpf_map__fd(g_skel->maps.tid_filter);

    for (uint32_t i = 0; i < AURORA_MAX_MONITORED_THREADS; i++) {
        if (before[i] <= 0)
            continue;
        const aurora_thread_metrics_t *m = &g_ts->threads[i];
        if (m->valid && m->tid == before[i])
            continue;

        uint32_t key = (uint32_t)before[i];
        if (stats_fd >= 0)
            bpf_map_delete_elem(stats_fd, &key);
        if (filter_fd >= 0)
            bpf_map_delete_elem(filter_fd, &key);
        g_prev[i].tid = 0;
    }
}

/* ---------------------------------------------------------------
 * Start the next collection interval: quanta recorded from now on count
 * towards the next per-interval maximum.
 * --------------------------------------------------------------- */
static void ebpf_publish_epoch(void)
{
    int epoch_fd = bpf_map__fd(g_skel->maps.interval_epoch);
    if (epoch_fd < 0)
        return;
    __u32 key = 0;
    bpf_map_update_elem(epoch_fd, &key, &g_epoch, BPF_ANY);
}

/* ---------------------------------------------------------------
 * One collection step (OCUDU: driven synchronously by the AURORA
 * publisher once per interval instead of a free-running thread, so the
 * published interval is complete and the BPF skeleton is never destroyed
 * while a collector thread still reads its maps).
 * --------------------------------------------------------------- */
void aurora_ebpf_collect_once(void)
{
    if (!g_skel)
        return;

    /* Discover new threads (and free the slots of exited ones) */
    pid_t before[AURORA_MAX_MONITORED_THREADS];
    for (uint32_t i = 0; i < AURORA_MAX_MONITORED_THREADS; i++)
        before[i] = g_ts->threads[i].valid ? g_ts->threads[i].tid : 0;
    aurora_thread_discover(g_ts);
    ebpf_forget_exited_threads(before);

    /* Update TID filter for newly discovered threads */
    ebpf_update_tid_filter();

    /* Merge BPF map data into the stats buffer */
    ebpf_read_and_merge();

    /* Close the interval */
    g_epoch++;
    ebpf_publish_epoch();

    /* Recompute derived statistics */
    aurora_thread_compute_all_stats(g_ts);
}

