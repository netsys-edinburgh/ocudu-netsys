/*
 * aurora_thread_ebpf.c — libbpf user-space agent for thread metrics collection.
 *
 * Compiled only when AURORA_THREAD_EBPF_ENABLED is defined (i.e., libbpf found).
 *
 * This module:
 *   1. Loads and attaches the BPF programs from aurora_thread_ebpf.skel.h
 *      (auto-generated by bpftool from the compiled .bpf.o object).
 *   2. Populates the tid_filter BPF map with registered TIDs.
 *   3. Runs a collection loop: reads BPF maps and merges data into shared memory.
 *   4. Falls back to aurora_thread_proc.c if eBPF attachment fails.
 */

#ifdef AURORA_THREAD_EBPF_ENABLED

#include "aurora_thread.h"
#include "aurora_thread_ebpf.h"
#include "aurora_thread_ebpf.skel.h"  /* auto-generated by bpftool gen skeleton */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <pthread.h>
#include <time.h>
#include <errno.h>
#include <sys/types.h>
#include <sys/stat.h>
#include <bpf/libbpf.h>
#include <bpf/bpf.h>

/* External declarations from aurora_thread_proc.c (fallback) */
int  aurora_procfs_start(aurora_thread_stats_t *ts, uint32_t interval_ms);
void aurora_procfs_stop(void);

/* External declarations from aurora_thread_registry.c */
void aurora_thread_registry_init(const aurora_thread_config_t *cfg);
void aurora_thread_discover(aurora_thread_stats_t *ts);

/* ---------------------------------------------------------------
 * Module-private state
 * --------------------------------------------------------------- */
static aurora_thread_stats_t          *g_ts = NULL;
static uint32_t                        g_interval_ms = 100;
static struct aurora_thread_ebpf_bpf  *g_skel = NULL;

/* ---------------------------------------------------------------
 * Identify our own pid namespace, so the BPF program can translate raw
 * host-namespace tracepoint TIDs into the same namespace
 * aurora_thread_registry.c's /proc/self/task walk uses (see
 * aurora_thread_ebpf.bpf.c's file header for why this is required —
 * without it, TID collisions with unrelated host/other-container tasks
 * silently corrupt the collected data whenever this runs in a container).
 * --------------------------------------------------------------- */
static int get_own_pidns_id(__u64 *dev_out, __u64 *ino_out)
{
    struct stat st;
    if (stat("/proc/self/ns/pid", &st) != 0) {
        fprintf(stderr, "AURORA: stat(/proc/self/ns/pid) failed: %s\n", strerror(errno));
        return -1;
    }
    *dev_out = (__u64)st.st_dev;
    *ino_out = (__u64)st.st_ino;
    return 0;
}

/* ---------------------------------------------------------------
 * Populate tid_filter map with all currently registered TIDs
 * --------------------------------------------------------------- */
static void ebpf_update_tid_filter(void)
{
    if (!g_skel || !g_ts)
        return;

    int filter_fd = bpf_map__fd(g_skel->maps.tid_filter);
    if (filter_fd < 0)
        return;

    uint32_t n = atomic_load_explicit(&g_ts->num_threads, memory_order_relaxed);
    for (uint32_t i = 0; i < n && i < AURORA_MAX_MONITORED_THREADS; i++) {
        aurora_thread_metrics_t *m = &g_ts->threads[i];
        if (!m->valid || m->tid <= 0)
            continue;
        uint32_t tid = (uint32_t)m->tid;
        uint8_t  val = 1;
        bpf_map_update_elem(filter_fd, &tid, &val, BPF_ANY);
    }
}

/* ---------------------------------------------------------------
 * Read BPF tid_stats map and merge into shared memory
 * --------------------------------------------------------------- */
static void ebpf_read_and_merge(void)
{
    if (!g_skel || !g_ts)
        return;

    int stats_fd = bpf_map__fd(g_skel->maps.tid_stats);
    if (stats_fd < 0)
        return;

    struct timespec ts_now;
    clock_gettime(CLOCK_MONOTONIC, &ts_now);
    uint64_t now_ns = (uint64_t)ts_now.tv_sec * 1000000000ULL + (uint64_t)ts_now.tv_nsec;

    /* Iterate all entries in the BPF hash map */
    uint32_t key = 0, next_key = 0;
    int first = 1;
    while (1) {
        int ret;
        if (first) {
            ret = bpf_map_get_next_key(stats_fd, NULL, &next_key);
            first = 0;
        } else {
            ret = bpf_map_get_next_key(stats_fd, &key, &next_key);
        }
        if (ret != 0)
            break;
        key = next_key;

        struct aurora_bpf_thread_stats bpf_s = {0};
        if (bpf_map_lookup_elem(stats_fd, &key, &bpf_s) != 0)
            continue;

        /* Find matching slot in shared memory */
        int slot = aurora_thread_find_slot(g_ts, (pid_t)key);
        if (slot < 0)
            continue;

        aurora_thread_metrics_t *m = &g_ts->threads[slot];

        /* Merge histogram: add BPF counts to shm histogram */
        for (int i = 0; i < AURORA_THREAD_HIST_BINS; i++)
            m->hist_runtime.bin[i] += bpf_s.hist_runtime[i];
        m->hist_runtime.overflow += bpf_s.overflow;
        m->total_events          += bpf_s.total_events;

        /* Update max */
        if (bpf_s.max_runtime_ns > m->max_runtime_ns)
            m->max_runtime_ns = bpf_s.max_runtime_ns;

        m->irq_count         += bpf_s.irq_count;
        m->voluntary_ctxsw   += bpf_s.voluntary_ctxsw;
        m->involuntary_ctxsw += bpf_s.involuntary_ctxsw;
        m->cpu_migrations    += bpf_s.cpu_migrations;
        if (bpf_s.last_cpu != AURORA_BPF_CPU_UNSET)
            m->cpu_id = (int)bpf_s.last_cpu;
        m->timestamp_ns = now_ns;

        /* Clear per-interval counters but keep last_cpu (a gauge, not a
         * delta) so a thread that doesn't run before the next merge still
         * reports its true last-known CPU instead of a zeroed sentinel. */
        struct aurora_bpf_thread_stats zero = {0};
        zero.pid = bpf_s.pid;
        zero.last_cpu = bpf_s.last_cpu;
        bpf_map_update_elem(stats_fd, &key, &zero, BPF_EXIST);
    }
}

/* ---------------------------------------------------------------
 * One collection step (OCUDU: driven synchronously by the AURORA
 * publisher once per interval instead of a free-running thread, so the
 * published interval is complete and the BPF skeleton is never destroyed
 * while a collector thread still reads its maps).
 * --------------------------------------------------------------- */
void aurora_ebpf_collect_once(void)
{
    if (!g_skel)
        return;

    /* Discover new threads */
    aurora_thread_discover(g_ts);

    /* Update TID filter for newly discovered threads */
    ebpf_update_tid_filter();

    /* Merge BPF map data into the stats buffer */
    ebpf_read_and_merge();

    /* Recompute derived statistics */
    aurora_thread_compute_all_stats(g_ts);
}

/* ---------------------------------------------------------------
 * Public API
 * --------------------------------------------------------------- */

/*
 * aurora_ebpf_start — load BPF programs, attach tracepoints, start loop.
 * Returns 0 on success, -1 if eBPF is unavailable (falls back to procfs).
 */
int aurora_ebpf_start(aurora_thread_stats_t *ts, uint32_t interval_ms)
{
    g_ts          = ts;
    g_interval_ms = interval_ms;

    __u64 ns_dev, ns_ino;
    if (get_own_pidns_id(&ns_dev, &ns_ino) != 0) {
        fprintf(stderr, "AURORA: could not identify own pid namespace, falling back to procfs\n");
        return -1;
    }

    /* Open (but don't yet load) so .rodata can be populated first — the
     * combined open_and_load() helper loads immediately, too late to set
     * aurora_target_ns_dev/ino before the verifier processes the program. */
    g_skel = aurora_thread_ebpf_bpf__open();
    if (!g_skel) {
        fprintf(stderr, "AURORA: eBPF open failed (errno=%d), falling back to procfs\n", errno);
        return -1;
    }

    g_skel->rodata->aurora_target_ns_dev = ns_dev;
    g_skel->rodata->aurora_target_ns_ino = ns_ino;

    if (aurora_thread_ebpf_bpf__load(g_skel) != 0) {
        fprintf(stderr, "AURORA: eBPF load failed (errno=%d), falling back to procfs\n", errno);
        aurora_thread_ebpf_bpf__destroy(g_skel);
        g_skel = NULL;
        return -1;
    }

    /* Attach tracepoints */
    int ret = aurora_thread_ebpf_bpf__attach(g_skel);
    if (ret != 0) {
        fprintf(stderr, "AURORA: eBPF attach failed (ret=%d), falling back to procfs\n", ret);
        aurora_thread_ebpf_bpf__destroy(g_skel);
        g_skel = NULL;
        return -1;
    }

    /* Populate initial TID filter */
    ebpf_update_tid_filter();

    return 0;
}

void aurora_ebpf_stop(void)
{
    if (g_skel) {
        aurora_thread_ebpf_bpf__destroy(g_skel);
        g_skel = NULL;
    }
}

#endif /* AURORA_THREAD_EBPF_ENABLED */
